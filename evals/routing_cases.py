#!/usr/bin/env python3
"""Generate evals/routing-cases.json — the routing eval suite for native invocation.

Why generated, not hand-typed: the spec (D1) requires positive prompts to be VERBATIM trigger
phrases from each skill's own `description`, because the description IS the routing surface
Claude matches against (ADR #2). Extracting them here means the suite cannot drift from the
descriptions — change a phrase in a SKILL.md and the eval changes with it.

Per skill: the first English `'…'` phrase and the first Russian `«…»` phrase. Plus hand-written
borderline prompts for the four confusable pairs (D1), each stating which neighbour must NOT
fire. Total ≈ 34 (the playbook's 20–50).

The JSON shape is deliberately close to a `claude plugin eval` case (prompt + expected
`tool_used: Skill`) so it converts unchanged once that command leaves early access; until then
scripts/test_routing_evals.sh drives it through headless `claude -p`.

Usage: python3 evals/routing_cases.py            # writes evals/routing-cases.json
       python3 evals/routing_cases.py --check    # exit 1 if the file is stale vs SKILL.md
"""
import glob, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "evals" / "routing-cases.json"

# Same description extraction as scripts/validate.sh §8 — one regex, one implementation.
DESC_RE = re.compile(r"^description:[ \t]*(.+?)(?=^\w+:|^---)", re.M | re.S)
# A quote counts as a phrase delimiter only when it is not glued to a word — otherwise
# "repo's installed hooks" would open a phrase at the apostrophe (seen: upgrade's
# description produced "s installed Strata hooks might be…" as a "trigger").
EN_RE = re.compile(r"(?<!\w)'([^']{4,})'(?!\w)")
RU_RE = re.compile(r"«([^»]{4,})»")

# Borderline prompts: wording leans toward the neighbour's vocabulary, intent belongs to `expect`.
NEGATIVES = [
    ("feature",      "refactor",     "поменяй поведение валидации — сейчас она пропускает пустые строки, а не должна"),
    ("refactor",     "feature",      "почини находки из аудита: убери дублирование в хелперах, поведение не менять"),
    ("office-hours", "lean-plan",    "есть идея — добавить экспорт в CSV; стоит ли это вообще делать?"),
    ("lean-plan",    "office-hours", "напиши план для экспорта в CSV — идею уже обсудили и приняли"),
    ("wiki-ingest",  "using-strata", "как у нас работает авторизация и где она лежит?"),
    ("using-strata", "wiki-ingest",  "что тут вообще есть и с чего начать в этом репо?"),
    ("upgrade",      "adopt",        "страта отстала — подтяни обновления хуков в этом репо"),
    ("adopt",        "upgrade",      "подключи страту к этому проекту, тут её ещё никогда не было"),
]


def skill_descriptions():
    for path in sorted(glob.glob(str(ROOT / "skills" / "*" / "SKILL.md"))):
        name = Path(path).parent.name
        text = Path(path).read_text(encoding="utf-8")
        m = DESC_RE.search(text)
        desc = " ".join(m.group(1).split()) if m else ""
        yield name, desc


def build():
    cases = []
    for name, desc in skill_descriptions():
        en = EN_RE.search(desc)
        ru = RU_RE.search(desc)
        if not en or not ru:
            print(f"  ! {name}: description lacks an EN '…' or RU «…» trigger phrase", file=sys.stderr)
            sys.exit(1)
        cases.append({"id": f"routing-{name}-en", "prompt": en.group(1), "expect": name, "kind": "positive"})
        cases.append({"id": f"routing-{name}-ru", "prompt": ru.group(1), "expect": name, "kind": "positive"})
    for expect, must_not, prompt in NEGATIVES:
        cases.append({"id": f"routing-{expect}-neg-{must_not}", "prompt": prompt, "expect": expect,
                      "must_not": must_not, "kind": "negative"})
    return {"_note": "generated by evals/routing_cases.py from skills/*/SKILL.md descriptions — do not hand-edit positives",
            "grader": "tool_used: Skill — the first Skill call's `skill` must equal strata:<expect>",
            "cases": cases}


def main():
    data = build()
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("evals/routing-cases.json is stale — run: python3 evals/routing_cases.py", file=sys.stderr)
            sys.exit(1)
        print(f"routing-cases.json current ({len(data['cases'])} cases)")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} — {len(data['cases'])} cases")


if __name__ == "__main__":
    main()
